def main():
    catalog, out = sys.argv[1], sys.argv[2]
    names = {s['name'] for s in json.load(open(catalog, encoding='utf-8'))['symbols']}
    missing = sorted({sym for _, syms in S.values() for sym in syms if sym not in names})
    if missing:
        sys.exit('not in catalog: ' + ', '.join(missing))
    overlap = set(S) & set(DECORATIVE)
    if overlap:
        sys.exit('both icon and decorative: ' + ', '.join(sorted(overlap)))
    icons = {name: {'title': title, 'symbols': symbols} for name, (title, symbols) in sorted(S.items(), key=lambda kv: kv[0].lower())}
    for name, kind in DECORATIVE.items():
        icons[name] = {'title': kind, 'symbols': [], 'decorative': True}
    data = {'version': 1, 'source': 'WeChat 8.0.73', 'icons': dict(sorted(icons.items(), key=lambda kv: kv[0].lower()))}
    with open(out, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print(f'{len(S)} icons with symbols, {len(DECORATIVE)} decorative')


if __name__ == '__main__':
    main()
